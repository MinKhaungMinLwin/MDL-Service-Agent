export type Messages = (typeof messages)[Locale];

export function getMessages(locale: Locale): Messages {
  return messages[locale];
}

export function getNavLabel(locale: Locale, id: SectionId): string {
  return getMessages(locale).nav[id];
}

export function getSidebarConfig(locale: Locale, section: SectionId) {
  const t = getMessages(locale);
  switch (section) {
    case "overview":
      return {
        title: t.sidebar.overview,
        items: OVERVIEW_SLUGS.map(({ slug, file }) => ({
          href: slug ? `/overview/${slug}` : "/overview",
          label: overviewLabels[locale][file],
        })),
      };
    case "backlog":
      return {
        title: t.sidebar.backlog,
        items: [{ href: "/task", label: t.sidebar.backlogIa }],
      };
    case "work":
      return {
        title: t.sidebar.work,
        items: [
          { href: "/work/backlog", label: t.sidebar.workBacklog },
          { href: "/work/kanban", label: t.sidebar.workKanban },
        ],
      };
    case "wbs":
      return {
        title: t.sidebar.wbs,
        items: [{ href: "/wbs", label: t.sidebar.wbsProgress }],
      };
    case "issues":
      return {
        title: t.sidebar.issues,
        items: [{ href: "/issues", label: t.sidebar.issuesList }],
      };
    case "agents":
      return {
        title: t.sidebar.agents,
        items: [{ href: "/agents", label: t.sidebar.agentsList }],
      };
    case "settings":
      return {
        title: t.sidebar.settings,
        items: [{ href: "/settings/users", label: t.sidebar.settingsUsers }],
      };
  }
}

const TASK_STATUS_MAP: Record<TaskStatus, keyof Messages["backlog"]> = {
  완료: "statusDone",
  진행중: "statusProgress",
  진행예정: "statusTodo",
};

export function taskStatusLabel(locale: Locale, status: TaskStatus): string {
  const key = TASK_STATUS_MAP[status];
  return getMessages(locale).backlog[key];
}

export function formatMessage(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key) => String(vars[key] ?? ""));
}
